/**
 * Walk a dotted key ("live.activeQueue") through a table.
 * Returns undefined when any segment is missing so the caller can fall back.
 */
export const lookup = (table, key) =>
  String(key)
    .split('.')
    .reduce((node, segment) => (node == null ? undefined : node[segment]), table);

/** Replace {placeholders} in a template with the given values. */
export const interpolate = (template, values = {}) =>
  String(template).replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match
  );
